@register.simple_tag
def icon(
    name: str,
    css_class: str = "size-5",
    stroke_width: str = "1.5",
    title: str = "",
    fill: str = "none",
):
    """Render an inline SVG. Unknown names render nothing rather than breaking a page.

    `fill="currentColor"` gives the solid variant of an outline glyph — used for
    on/off pairs such as a saved bookmark, where a second icon file would be a
    second source of truth.
    """
    path = PATHS.get(name)
    if path is None:
        return mark_safe("")

    label = format_html("<title>{}</title>", title) if title else mark_safe("")
    return format_html(
        '<svg class="{}" viewBox="0 0 24 24" fill="{}" stroke="currentColor" '
        'stroke-width="{}" stroke-linecap="round" stroke-linejoin="round" '
        'aria-hidden="{}" {}>{}<path d="{}"/></svg>',
        css_class,
        fill,
        stroke_width,
        "false" if title else "true",
        mark_safe('role="img"' if title else ""),  # noqa: S308 - literal, not user input
        label,
        mark_safe(path),  # noqa: S308 - path data comes from the icon registry, not a request
    )


@register.simple_tag
def has_icon(name: str) -> bool:
    return name in PATHS
