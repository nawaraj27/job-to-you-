"""
Suggestions: proposed edits to a draft, and the accept that applies them (INV-3).

The invariant this makes structural is "nothing writes to a candidate's
document without an explicit accept". P5 fills the table from the reconcile
protocol; P12 adds AI-generated wording. The accept path does not change,
which is the point — by the time a model is proposing text, the only way into a
draft is already a row the candidate has to say yes to.

An accept writes through `drafts._edit` like every other change, so it is
snapshotted, undoable and optimistically locked exactly like a hand edit.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from django.db import transaction
from django.utils import timezone

from apps.ai.models import AIRun
from apps.audit import services as audit
from apps.common.errors import InvalidState, NotFound

from .. import content as content_rules
from ..models import ResumeDraft, ResumeFinding, ResumeSuggestion, SuggestionState
from . import drafts as draft_service

if TYPE_CHECKING:  # pragma: no cover
    from apps.accounts.models import User


@transaction.atomic
def offer(
    *,
    draft: ResumeDraft,
    target_path: str,
    proposed: str,
    original: str = "",
    source: str = "reconcile",
    rationale: str = "",
    ai_run: AIRun | None = None,
    finding: ResumeFinding | None = None,
) -> ResumeSuggestion:
    """Propose one edit. Idempotent per (target, proposed).

    Re-running the reconcile protocol every time a profile changes would
    otherwise stack duplicate suggestions for the same drift, and a list with
    the same sentence four times is a list nobody reads.

    `ai_run` and `finding` are the attributions an AI-authored suggestion needs
    (ADR-A11). They are parameters rather than a second write by the caller:
    P12's `apply_finding` created the row here and then patched both fields
    afterwards, which left a suggestion briefly existing with no attribution and
    meant every future AI caller would copy the patch. P14 added the second such
    caller, so the shape moved here instead.
    """
    if not proposed.strip():
        raise InvalidState("A suggestion needs something to propose.")

    existing = draft.suggestions.filter(
        target_path=target_path, proposed=proposed, state=SuggestionState.OFFERED
    ).first()
    if existing is not None:
        return existing

    return ResumeSuggestion.objects.create(
        draft=draft,
        target_path=target_path[:200],
        original=original,
        proposed=proposed,
        source=source,
        rationale=rationale[:200],
        ai_run=ai_run,
        finding=finding,
    )


@transaction.atomic
def accept(*, suggestion: ResumeSuggestion, actor: User) -> ResumeSuggestion:
    """Apply a suggestion to the draft. The only path from proposal to document."""
    if not suggestion.is_open:
        raise InvalidState("That suggestion has already been decided.")

    _apply(suggestion)

    suggestion.state = SuggestionState.ACCEPTED
    suggestion.decided_at = timezone.now()
    suggestion.decided_by = actor
    suggestion.save(update_fields=["state", "decided_at", "decided_by", "updated_at"])

    audit.record(
        verb="resume.suggestion_accepted",
        actor=actor,
        target=suggestion.draft.document,
        metadata={"path": suggestion.target_path, "source": suggestion.source},
    )
    return suggestion


@transaction.atomic
def reject(*, suggestion: ResumeSuggestion, actor: User) -> ResumeSuggestion:
    if not suggestion.is_open:
        raise InvalidState("That suggestion has already been decided.")

    suggestion.state = SuggestionState.REJECTED
    suggestion.decided_at = timezone.now()
    suggestion.decided_by = actor
    suggestion.save(update_fields=["state", "decided_at", "decided_by", "updated_at"])

    audit.record(
        verb="resume.suggestion_rejected",
        actor=actor,
        target=suggestion.draft.document,
        metadata={"path": suggestion.target_path},
    )
    return suggestion


def _apply(suggestion: ResumeSuggestion) -> None:
    """Write the proposed value at its target path.

    Paths are a small, closed vocabulary rather than a general expression
    language: a suggestion is generated by this codebase, and a path syntax
    that can address anything is a path syntax that can address the wrong thing.

        summary
        contact.headline
        entry.<entry_id>.bullets      — the whole list, rewritten
        entry.<entry_id>.bullet       — one more line, appended
        entry.<entry_id>.title
        section.<section_id>.items
        section.<section_id>.entry.<entry_id>.<field>

    The last one is for a role the candidate does not have yet — the assistant
    builder, where somebody with an empty CV describes a job. The entry id is
    reserved when the suggestion is offered and the role is created here, on
    accept, so the document is untouched until they say yes (INV-3) and every
    bullet from that conversation lands in the same role.
    """
    path = suggestion.target_path
    draft = suggestion.draft
    value = suggestion.proposed

    if path == "summary":
        section = content_rules.section_by_key(draft.content, "summary")
        if section is None:
            raise NotFound("This CV has no summary section.")
        draft_service.set_section_text(draft=draft, section_id=section["id"], text=value)
        return

    if path.startswith("contact."):
        draft_service.set_contact(draft=draft, field=path.split(".", 1)[1], value=value)
        return

    parts = path.split(".")
    if len(parts) == 5 and parts[0] == "section" and parts[2] == "entry":
        draft_service.ensure_entry(draft=draft, section_id=parts[1], entry_id=parts[3])
        _apply_to_entry(draft, entry_id=parts[3], field=parts[4], value=value)
        return

    if len(parts) == 3 and parts[0] == "entry":
        _apply_to_entry(draft, entry_id=parts[1], field=parts[2], value=value)
        return

    if len(parts) == 3 and parts[0] == "section" and parts[2] == "items":
        draft_service.set_section_items(
            draft=draft, section_id=parts[1], items=[line for line in value.split("\n") if line]
        )
        return

    raise InvalidState(f"{path!r} is not a place a suggestion can be applied.")


def _apply_to_entry(draft: ResumeDraft, *, entry_id: str, field: str, value: str) -> None:
    if field == "bullets":
        # The plural is a replacement: the whole list, rewritten. That is what
        # the analysis fix proposes, and it hands back every original line.
        draft_service.set_bullets(
            draft=draft, entry_id=entry_id, bullets=[line for line in value.split("\n") if line]
        )
        return

    if field == "bullet":
        # The singular adds one. The assistant proposes a bullet at a time, and
        # every one of them was a replacement — so a candidate who accepted
        # three bullets from one answer kept the third, and whatever was
        # already written on that role went with the first accept.
        located = content_rules.entry_by_id(draft.content, entry_id)
        if located is None:
            raise NotFound("That role is not in this CV.")

        existing = list(located[1].get("bullets") or [])
        line = value.strip()
        if line and line not in existing:
            existing.append(line)
        draft_service.set_bullets(draft=draft, entry_id=entry_id, bullets=existing)
        return

    if field in {"title", "org", "dates"}:
        draft_service.update_entry(draft=draft, entry_id=entry_id, **{field: value})
        return

    raise InvalidState(f"{field!r} is not an editable part of an entry.")
