class SkillQuerySet(models.QuerySet):
    def active(self) -> SkillQuerySet:
        """Skills that may be attached to new records."""
        return self.filter(status=SkillStatus.ACTIVE)

    def retired(self) -> SkillQuerySet:
        return self.exclude(status=SkillStatus.ACTIVE)


class Skill(TimeStampedModel):
    slug = models.SlugField(max_length=100, unique=True)
    name = models.CharField(max_length=120, help_text="Canonical English label.")
    category = models.ForeignKey(
        SkillCategory, null=True, blank=True, on_delete=models.SET_NULL, related_name="skills"
    )
    description = models.TextField(blank=True)
    kind = models.CharField(
        max_length=24,
        choices=SkillKind.choices,
        default=SkillKind.UNKNOWN,
        help_text="What sort of skill this is. Independent of category (ADR-A48).",
    )

    status = models.CharField(
        max_length=16, choices=SkillStatus.choices, default=SkillStatus.ACTIVE
    )
    replaced_by = models.ForeignKey(
        "self",
        null=True,
        blank=True,
        on_delete=models.PROTECT,
        related_name="replaces",
        help_text=(
            "Where this skill's meaning now lives. Set for merged duplicates and for "
            "deprecated skills with a successor. PROTECT, so a replacement cannot be "
            "deleted out from under the skills forwarding to it."
        ),
    )
    retired_reason = models.CharField(max_length=255, blank=True)
    retired_at = models.DateTimeField(null=True, blank=True)

    usage_count = models.PositiveIntegerField(
        default=0, help_text="Denormalised. Updated asynchronously; never authoritative."
    )

    objects = SkillQuerySet.as_manager()

    class Meta:
        ordering = ("name",)
        indexes = [
            models.Index(fields=["name"], name="skill_name_idx"),
            # The trigram fallback in resolution is a similarity scan. Without
            # this it is a sequential one over every skill, on a path that runs
            # once per unrecognised term in every resume parsed.
            GinIndex(fields=["name"], name="skill_name_trgm_idx", opclasses=["gin_trgm_ops"]),
            models.Index(
                fields=["status"],
                condition=models.Q(status="active"),
                name="skill_active_idx",
            ),
            models.Index(fields=["kind"], name="skill_kind_idx"),
        ]
        constraints = [
            # An active skill cannot forward anywhere, and a merged one must.
            # A deprecated skill may or may not have a successor: sometimes a
            # technology simply stops being asked for.
            models.CheckConstraint(
                condition=(
                    models.Q(status="active", replaced_by__isnull=True)
                    | models.Q(status="deprecated")
                    | models.Q(status="merged", replaced_by__isnull=False)
                ),
                name="skill_replacement_matches_status",
            ),
        ]

    def __str__(self) -> str:
        return self.name

    @property
    def is_active(self) -> bool:
        return self.status == SkillStatus.ACTIVE

    @property
    def is_retired(self) -> bool:
        return self.status != SkillStatus.ACTIVE

    def resolve_current(self) -> Skill:
        """Follow the replacement chain to the skill in service today.

        Bounded rather than recursive: a curation mistake that produces a cycle
        must not hang a request. A deprecated skill with no successor resolves
        to itself — it is still the most accurate name for what someone knows.
        """
        seen: set[int] = set()
        skill: Skill = self
        while skill.replaced_by_id is not None and skill.pk not in seen:
            seen.add(skill.pk)
            nxt = skill.replaced_by
            if nxt is None:
                break
            skill = nxt
        return skill

    def display_name(self, locale: str = "en") -> str:
        """The label for a locale, falling back to the canonical English name."""
        if locale == "en":
            return self.name
        translation = self.translations.filter(locale=locale).first()
        return translation.name if translation else self.name


class SkillTranslation(TimeStampedModel):
    """A display name in one locale.

    Separate from `SkillAlias` on purpose: a translation is what the interface
    *shows*, an alias is what resolution *accepts*. Nepali for "Accounting"
    belongs here; "acctg" belongs in aliases. Conflating them would put every
    typo on screen.
    """

    skill = models.ForeignKey(Skill, on_delete=models.CASCADE, related_name="translations")
    locale = models.CharField(max_length=10)
    name = models.CharField(max_length=120)
    description = models.TextField(blank=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=["skill", "locale"], name="skilltranslation_one_per_locale"
            )
        ]

    def __str__(self) -> str:
        return f"{self.name} ({self.locale})"


class SkillExternalId(TimeStampedModel):
    """A skill's identity in an external taxonomy.

    A table rather than a column because the platform will import from more than
    one source, and a single `esco_uri` field forces the second importer either
    to overwrite the first or to invent a parallel field. Both are worse than a
    join.
    """

    skill = models.ForeignKey(Skill, on_delete=models.CASCADE, related_name="external_ids")
    source = models.CharField(max_length=40, help_text="esco, onet, lightcast, ...")
    external_id = models.CharField(max_length=200)
    uri = models.URLField(blank=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=["source", "external_id"], name="skillexternalid_unique_per_source"
            )
        ]
        indexes = [models.Index(fields=["source"], name="skillexternalid_source_idx")]

    def __str__(self) -> str:
        return f"{self.source}:{self.external_id}"


class ProvenancedModel(models.Model):
    """Who asserted this, how sure they were, and which run wrote it (ADR-A47).

    Carried by aliases and relations because both will soon be written by
    machines as well as people. `batch` is what makes an inference run
    reversible: without it, undoing a bad batch means guessing which rows it
    created, and the guess is wrong in exactly the cases that matter.
    """

    source = models.CharField(
        max_length=16,
        choices=Provenance.choices,
        default=Provenance.CURATED,
        # Blank in forms, never blank in the column: a curator adding an alias
        # by hand should not have to answer "who is asserting this".
        blank=True,
    )
    confidence = models.DecimalField(
        max_digits=3,
        decimal_places=2,
        null=True,
        blank=True,
        validators=[MinValueValidator(0), MaxValueValidator(1)],
        help_text="How sure the writer was. Null for curated work, which is not a guess.",
    )
    created_by = models.ForeignKey(
        "accounts.User",
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="+",
        help_text="The person, where there was one. Null for imports and inference.",
    )
    created_reason = models.CharField(
        max_length=200,
        blank=True,
        help_text="Why this was asserted: the import run, the model, or the curator's note.",
    )
    batch = models.CharField(
        max_length=64,
        blank=True,
        help_text="Groups one machine-written run so it can be reverted whole.",
    )

    class Meta:
        abstract = True

    @property
    def is_machine_written(self) -> bool:
        return self.source in REVERSIBLE_PROVENANCE


class SkillAlias(ProvenancedModel, TimeStampedModel):
    """A surface form resolution accepts. "JS" and "ECMAScript" are JavaScript.

    Exact alias lookup is what makes resolution trustworthy; the trigram
    fallback in `services.skills` only runs when no alias matches, because
    "Java" is three characters from "JavaScript" and a fuzzy match allowed to
    beat an exact one is how a candidate's Java experience silently becomes
    JavaScript.
    """

    skill = models.ForeignKey(Skill, on_delete=models.CASCADE, related_name="aliases")
    alias = models.CharField(max_length=120)
    normalised = models.CharField(
        max_length=120,
        blank=True,
        help_text="Derived from the alias. The column actually matched against.",
    )
    locale = models.CharField(max_length=10, default="en")

    class Meta:
        verbose_name_plural = "skill aliases"
        constraints = [
            models.UniqueConstraint(
                fields=["normalised", "locale"], name="skillalias_unique_per_locale"
            )
        ]
        indexes = [
            models.Index(fields=["normalised"], name="skillalias_normalised_idx"),
            models.Index(fields=["batch"], name="skillalias_batch_idx"),
        ]

    def __str__(self) -> str:
        return f"{self.alias} -> {self.skill_id}"

    def save(self, *args, **kwargs):
        # Derived here rather than by each caller, because an alias whose
        # `normalised` does not match how resolution normalises input is an
        # alias that matches nothing, with no error anywhere to show it.
        self.normalised = normalise(self.alias)
        if "update_fields" in kwargs and kwargs["update_fields"] is not None:
            kwargs["update_fields"] = {*kwargs["update_fields"], "normalised"}
        return super().save(*args, **kwargs)


