class Location(TimeStampedModel):
    """Normalised place, so "Kathmandu" is one row rather than forty strings."""

    country = models.CharField(max_length=2, help_text="ISO 3166-1 alpha-2.")
    region = models.CharField(max_length=120, blank=True)
    city = models.CharField(max_length=120)
    geoname_id = models.PositiveIntegerField(null=True, blank=True, unique=True)
    latitude = models.DecimalField(max_digits=9, decimal_places=6, null=True, blank=True)
    longitude = models.DecimalField(max_digits=9, decimal_places=6, null=True, blank=True)
    timezone = models.CharField(max_length=64, blank=True)

    class Meta:
        ordering = ("country", "city")
        constraints = [
            models.UniqueConstraint(
                fields=["country", "region", "city"], name="location_unique_place"
            )
        ]
        indexes = [models.Index(fields=["city"], name="location_city_idx")]

    def __str__(self) -> str:
        return f"{self.city}, {self.country}"

    @property
    def name(self) -> str:
        """How a place is written on screen.

        One property rather than four templates each assembling it: a location
        printed as "Kathmandu" in a list and "Kathmandu, NP" on a detail page
        looks like two different places to the person reading both.
        """
        return self.city or self.region or self.country


