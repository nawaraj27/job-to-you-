"""
Reference data (SRS §5.3, ADR-A13).

The skill taxonomy is infrastructure, not a feature. Matching, gap analysis,
missing-skill demand, employer filters and learning recommendations all read it,
and every one of them is worthless if "JS", "JavaScript" and "ECMAScript" are
three rows, or if the system does not know that Django implies Python.

Designed so the taxonomy can evolve without breaking the data already attached
to it:

  * **Nothing is deleted.** A skill leaves service by changing `status`, never
    by disappearing — a deleted skill would orphan every alias, relation and
    (from P3) every CandidateSkill that referenced it, and make a curation
    mistake unrecoverable.
  * **Merge and deprecation are different facts.** A merged skill *always was*
    the same thing as its replacement — a duplicate row. A deprecated skill was
    genuinely distinct and is now obsolete: AngularJS was never Angular. Both
    forward through `replaced_by`, and the distinction survives in `status` for
    anyone auditing why a profile changed meaning.
  * **External identity is pluggable.** `SkillExternalId` carries (source, id)
    pairs, so ESCO, O*NET and whatever comes next coexist rather than one
    winning a column.
  * **Names are not English-only.** `SkillTranslation` holds per-locale display
    names; `Skill.name` is the canonical English label, not the only one.

`FxRate` is here for the same reason: a salary in NPR per month and one in USD
per year cannot be compared until both are annualised in one base, and the rate
that did it has to be recoverable years later (ADR-A39).
"""

from __future__ import annotations

