class UnresolvedTerm(TimeStampedModel):
    """A term the taxonomy did not recognise (ADR-A46).

    The system refuses to invent a skill per typo, which is right — and the
    consequence, without this table, is that the term is simply lost. It is
    lost for the curator who would have added the missing skill, for
    emerging-skill tracking, and for demand analysis, none of which can be
    backfilled: a term nobody recorded cannot be recovered from anywhere.

    One row per (normalised, locale) so the queue reads as a list of distinct
    gaps. `source_counts` keeps the per-channel evidence, because a term typed
    by fifty candidates and one extracted by a model are not equally strong
    arguments for adding a skill.
    """

    term = models.CharField(max_length=200, help_text="The first spelling seen, verbatim.")
    normalised = models.CharField(max_length=200, db_index=True)
    locale = models.CharField(max_length=10, default="en")

    occurrences = models.PositiveIntegerField(default=1)
    first_seen = models.DateTimeField(auto_now_add=True)
    last_seen = models.DateTimeField(auto_now=True)

    source = models.CharField(
        max_length=20,
        choices=TermSource.choices,
        default=TermSource.OTHER,
        help_text="Most recent channel this term arrived through.",
    )
    source_counts = models.JSONField(
        default=dict, blank=True, help_text="Per-channel occurrence counts."
    )
    confidence = models.DecimalField(
        max_digits=3,
        decimal_places=2,
        null=True,
        blank=True,
        validators=[MinValueValidator(0), MaxValueValidator(1)],
        help_text="Extractor confidence, where the source had one.",
    )

    status = models.CharField(max_length=16, choices=TermStatus.choices, default=TermStatus.PENDING)
    resolved_skill = models.ForeignKey(
        "Skill",
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="resolved_terms",
        help_text="What a curator decided this means.",
    )
    resolved_by = models.ForeignKey(
        "accounts.User", null=True, blank=True, on_delete=models.SET_NULL, related_name="+"
    )
    resolved_at = models.DateTimeField(null=True, blank=True)
    resolution_note = models.CharField(max_length=200, blank=True)

    class Meta:
        ordering = ("-occurrences", "-last_seen")
        constraints = [
            models.UniqueConstraint(
                fields=["normalised", "locale"], name="unresolvedterm_once_per_locale"
            ),
            # A resolved term names the skill it resolved to; a pending or
            # rejected one must not, or the queue's counts stop meaning anything.
            models.CheckConstraint(
                condition=(
                    models.Q(status="resolved", resolved_skill__isnull=False)
                    | ~models.Q(status="resolved")
                ),
                name="unresolvedterm_resolved_has_skill",
            ),
        ]
        indexes = [
            models.Index(
                fields=["-occurrences"],
                condition=models.Q(status="pending"),
                name="unresolvedterm_queue_idx",
            ),
        ]

    def __str__(self) -> str:
        return f"{self.term} ({self.occurrences})"


