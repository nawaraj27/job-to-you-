class FxRate(models.Model):
    """A currency conversion rate, as of a date (ADR-A39).

    Append-only. A historical rate is superseded by a newer row, never edited:
    a match made last March must still be explicable this March, and editing
    the rate in place silently rewrites every conversion that used it.
    """

    base = models.CharField(max_length=3, help_text="ISO 4217, e.g. NPR.")
    quote = models.CharField(max_length=3, help_text="ISO 4217, e.g. USD.")
    rate = models.DecimalField(
        max_digits=20, decimal_places=10, help_text="1 base = this many quote."
    )
    as_of = models.DateField()
    source = models.CharField(max_length=60, help_text="Where the figure came from.")
    provider_ref = models.CharField(max_length=120, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ("-as_of",)
        constraints = [
            models.UniqueConstraint(
                fields=["base", "quote", "as_of"], name="fxrate_one_per_pair_per_day"
            ),
            models.CheckConstraint(condition=models.Q(rate__gt=0), name="fxrate_positive"),
        ]
        indexes = [models.Index(fields=["base", "quote", "-as_of"], name="fxrate_lookup_idx")]

    def __str__(self) -> str:
        return f"{self.base}/{self.quote} @ {self.as_of}: {self.rate}"

    def save(self, *args, **kwargs):
        if self.pk is not None:
            raise ValueError(
                "FxRate is append-only: supersede a rate with a newer as_of date "
                "rather than editing it, or every historical conversion silently changes."
            )
        self.base = self.base.upper()
        self.quote = self.quote.upper()
        return super().save(*args, **kwargs)
