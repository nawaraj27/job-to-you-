class RelationKind(models.TextChoices):
    """Typed edges between skills.

    `broader`/`narrower` form the hierarchy: Python is broader than Django.
    `implies` is what the matcher spends — knowing Django partly satisfies a
    Python requirement. `related` is a suggestion only and is deliberately
    worthless for scoring, because co-occurrence is not evidence.
    """

    BROADER = "broader", _("Broader than")
    NARROWER = "narrower", _("Narrower than")
    RELATED = "related", _("Related to")
    IMPLIES = "implies", _("Implies")


class SkillStatus(models.TextChoices):
    ACTIVE = "active", _("Active")
    DEPRECATED = "deprecated", _("Deprecated")
    MERGED = "merged", _("Merged into another skill")


class SkillKind(models.TextChoices):
    """What sort of thing a skill is (ADR-A48).

    Category answers "which part of the world is this from"; kind answers "what
    sort of claim is being made". They are independent: Python and Django are
    both engineering, and one is a language while the other is a framework.

    The matcher will weight kinds differently — a missing programming language
    is not the same gap as a missing methodology — and gap analysis, clustering
    and learning recommendations all need the distinction. Extensible by adding
    a member: nothing keys off the set, and `UNKNOWN` absorbs anything imported
    before a curator has looked at it.
    """

    UNKNOWN = "unknown", _("Not yet classified")
    HARD_SKILL = "hard_skill", _("Hard skill")
    SOFT_SKILL = "soft_skill", _("Soft skill")
    TOOL = "tool", _("Tool")
    TECHNOLOGY = "technology", _("Technology")
    PROGRAMMING_LANGUAGE = "programming_language", _("Programming language")
    FRAMEWORK = "framework", _("Framework")
    LIBRARY = "library", _("Library")
    PLATFORM = "platform", _("Platform")
    DOMAIN_KNOWLEDGE = "domain_knowledge", _("Domain knowledge")
    METHODOLOGY = "methodology", _("Methodology")
    CERTIFICATION = "certification", _("Certification")
    LANGUAGE = "language", _("Spoken language")


class Provenance(models.TextChoices):
    """Where an assertion came from (ADR-A47).

    Recorded on every alias and every relation, because P13 will start
    inferring edges from co-occurrence and a curated edge must never be
    indistinguishable from a guessed one. Without this, a bad inference batch
    is unrollbackable: nothing says which rows it wrote.
    """

    CURATED = "curated", _("Curated by staff")
    IMPORTED = "imported", _("Imported from an external taxonomy")
    INFERRED = "inferred", _("Inferred from data")
    AI_GENERATED = "ai_generated", _("Generated by a model")
    MANUAL = "manual", _("Created by hand in a one-off")


#: Provenances a batch revert may delete. Curated and imported assertions are
#: someone's deliberate work and are never removed by a machine-written undo.
REVERSIBLE_PROVENANCE = (Provenance.INFERRED, Provenance.AI_GENERATED)


